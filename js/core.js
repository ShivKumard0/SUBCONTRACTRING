/* ── Toast ──────────────────────────────────────────────────────────────────
   For confirmations only.  A blocked action explains itself where it was
   blocked, never in a toast that floats away before it is read. */
let toastTimer = null;
function toast(msg, tone) {
  const host = document.getElementById('toast-host');
  if (!host) return;
  /* A2 · role="status" + aria-live so a confirmation is announced rather than
     appearing silently for 3.6 seconds and vanishing. */
  host.innerHTML = '<div class="toast toast-' + (tone || 'ok') + '" role="status" aria-live="polite">' +
    '<span class="toast-msg">' + esc(msg) + '</span>' +
    '<button class="toast-close" onclick="dismissToast()" aria-label="Dismiss">&times;</button></div>';
  clearTimeout(toastTimer);
  toastTimer = setTimeout(dismissToast, 3600);
}
function dismissToast() {
  const host = document.getElementById('toast-host');
  if (host) host.innerHTML = '';
  clearTimeout(toastTimer);
}

/* ── Boot ───────────────────────────────────────────────────────────────── */
function boot() {
  /* ?as=u-security opens the app as that user. Deep-linking a role is what
     makes a demo walkthrough repeatable — you can hand someone a link to the
     exact queue you want them to look at instead of talking them through the
     switcher first. */
  const as = new URLSearchParams(location.search).get('as');

  /* Seeding runs as internal staff regardless of who is about to sign in, so
     the demo data is identical whichever role you open the app as. */
  if (typeof seedDemo === 'function') { currentUserId = 'u-planner'; seedDemo(); }
  if (as && USERS[as]) currentUserId = as;

  /* ?page=challans opens straight onto a screen. With ?as= this makes any
     point in the walkthrough a single link — which is what a demo script
     needs, and what makes each screen testable in isolation. */
  const pg = new URLSearchParams(location.search).get('page');
  if (pg && PAGE_TITLE[pg]) { page = pg; activeSidebarItem = pg; }

  /* ?open=SUB-000318 lands on a specific record's detail view. Together with
     ?as and ?page this makes every step of the walkthrough a single link. */
  const open = new URLSearchParams(location.search).get('open');
  if (open) openRecord(open);

  /* ?view=mobile opens the same screen on a phone. Part of the same demo-link
     set as ?as and ?page: "the approver's queue, as they see it" is a link,
     not three instructions.

     Applied LAST, after ?open has settled which screen we are on — otherwise
     it answers the question for the page named in the URL rather than the one
     the record actually opened. Without an explicit view the default is web,
     and only a decision waiting for this user opens a phone. */
  const vw = new URLSearchParams(location.search).get('view');
  channel = (vw === 'mobile' || vw === 'web') ? vw : channelForPage(page);

  renderTopbarUser();
  if (!can(page, 'v')) { page = firstAllowedPage(); activeSidebarItem = page; }
  /* F33 again, on the one route that was missed. Every other way into a child
     page — navigatePage, openRecord, openMobileTask, switchToStageActor —
     expands the dropdown that owns it. boot() did not, so ?page=delivery-notes
     landed with the active item inside a collapsed Documents group and nothing
     highlighted at all. That is the deep-link mechanism the whole demo script
     is built on. */
  expandOwningDropdown(page);
  buildSidebar();
  renderPage();
}
document.addEventListener('DOMContentLoaded', boot);
