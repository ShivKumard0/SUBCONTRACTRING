/* ── Sidebar ────────────────────────────────────────────────────────────────
   Rebuilt only when its signature changes, so a page repaint never disturbs an
   open dropdown.  Permission filtering happens HERE rather than at render
   time: a nav item you cannot open should not be visible at all, and a section
   or dropdown left empty by the filter removes itself with it. */
function sidebarSig() {
  return currentUserId + '|' + (sidebarCollapsed ? 1 : 0) + '|' + activeSidebarItem +
         '|' + Array.from(openDropdowns).sort().join(',');
}
let lastSidebarSig = null;

/* F33 · openDropdowns was only ever written by a click, so ANY other route to
   a child page — a deep link, a role switch, a redirect after an action — left
   the owning dropdown shut and the active item nowhere on screen. */
function expandOwningDropdown(pageId) {
  SIDEBAR.forEach(item => {
    if (item.dropdown && (item.children || []).some(c => c.id === pageId))
      openDropdowns.add(item.dropdown);
  });
}

function visibleChildren(item) {
  return (item.children || []).filter(c => can(c.id, 'v'));
}

function buildSidebar() {
  const el = document.getElementById('sidebar');
  if (!el) return;
  lastSidebarSig = sidebarSig();
  el.className = 'sidebar' + (sidebarCollapsed ? ' collapsed' : '');
  el.innerHTML = '';

  /* The product names itself in its own chrome. A sidebar starting with the
     word "MENU" is template furniture; this is where the module identity and
     the plant you are operating live. */
  const top = document.createElement('div');
  top.className = 'sb-top';
  top.innerHTML = (sidebarCollapsed ? '' :
      '<div class="sb-brand"><span class="sb-brand-name">Sub-Contracting</span>' +
      '<span class="sb-brand-sub">L&amp;T Trichy Works</span></div>') +
    '<button class="sidebar-toggle" onclick="toggleSidebar()" title="Toggle sidebar" aria-label="Toggle sidebar">' +
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><rect x="4" y="5" width="16" height="14" rx="2"/><line x1="15" y1="5" x2="15" y2="19"/></svg></button>';
  el.appendChild(top);

  /* A section header is held back until something under it survives the
     filter, so it can never be emitted above an empty stretch of nav. */
  let pendingSection = null;

  SIDEBAR.forEach(item => {
    if (item.section) { pendingSection = item.section; return; }

    const kids = item.dropdown ? visibleChildren(item) : null;
    if (item.dropdown ? !kids.length : !can(item.id, 'v')) return;

    if (pendingSection && !sidebarCollapsed) {
      const s = document.createElement('div');
      s.className = 'sb-section';
      s.textContent = pendingSection;
      el.appendChild(s);
    }
    pendingSection = null;

    if (item.dropdown) {
      const isOpen = openDropdowns.has(item.dropdown);
      const hasActive = kids.some(c => c.id === activeSidebarItem);
      if (!sidebarCollapsed) {
        const parent = document.createElement('button');
        parent.type = 'button';
        parent.className = 'sb-parent' + (isOpen ? ' open' : '') + (hasActive ? ' has-active' : '');
        parent.title = item.dropdown;
        parent.innerHTML = '<div class="sb-ico-wrap">' + (item.icon || '') + '</div><span>' + esc(item.dropdown) + '</span>' +
          '<svg class="sb-chev" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5"><polyline points="6 9 12 15 18 9"/></svg>';

        const box = document.createElement('div');
        box.className = 'sb-children';
        box.style.maxHeight = isOpen ? '600px' : '0';
        kids.forEach(child => {
          const b = document.createElement('button');
          b.type = 'button';
          b.className = 'sb-item' + (child.id === activeSidebarItem ? ' active' : '');
          b.title = child.label;
          b.innerHTML = '<div class="sb-ico-wrap">' + (child.icon || '') + '</div><span>' + esc(child.label) + '</span>';
          b.onclick = () => navigatePage(child.id);
          box.appendChild(b);
        });
        parent.onclick = () => {
          if (openDropdowns.has(item.dropdown)) {
            openDropdowns.delete(item.dropdown);
            box.style.maxHeight = '0';
            parent.classList.remove('open');
          } else {
            el.querySelectorAll('.sb-parent.open').forEach(p => p.classList.remove('open'));
            el.querySelectorAll('.sb-children').forEach(c => c.style.maxHeight = '0');
            openDropdowns.clear();
            openDropdowns.add(item.dropdown);
            box.style.maxHeight = '600px';
            parent.classList.add('open');
          }
        };
        el.appendChild(parent);
        el.appendChild(box);
      } else {
        const d = document.createElement('button');
        d.type = 'button';
        d.className = 'sb-parent' + (hasActive ? ' has-active' : '');
        d.title = item.dropdown;
        d.innerHTML = '<div class="sb-ico-wrap">' + (item.icon || '') + '</div>';
        d.onclick = () => {
          sidebarCollapsed = false;
          openDropdowns.clear();
          openDropdowns.add(item.dropdown);
          buildSidebar();
        };
        el.appendChild(d);
      }
      return;
    }

    const b = document.createElement('button');
    b.type = 'button';
    b.className = 'sb-item' + (item.id === activeSidebarItem ? ' active' : '');
    b.title = item.label;
    b.innerHTML = '<div class="sb-ico-wrap">' + (item.icon || '') + '</div><span>' + esc(item.label) + '</span>';
    b.onclick = () => navigatePage(item.id);
    el.appendChild(b);
  });
}

function toggleSidebar() {
  sidebarCollapsed = !sidebarCollapsed;
  if (sidebarCollapsed) openDropdowns.clear();
  buildSidebar();
}

/* The address bar follows you. Without this, copying the URL to share "the
   challan we're arguing about" silently shared your dashboard — the app read
   ?page=&open= inbound but never wrote them. */
let lastOpenedRecord = null;
function syncUrl() {
  try {
    const q = '?as=' + currentUserId + '&page=' + page + '&view=' + channel +
              (lastOpenedRecord ? '&open=' + lastOpenedRecord : '');
    history.replaceState(null, '', q);
  } catch (e) { /* file:// in some browsers refuses replaceState — fine */ }
}

/* `withFilter` lands the user on a PRE-FILTERED queue. A dashboard tile that
   says "Requests to approve · 1" and then opens the full nine-row list with
   the filter on All was promising a queue and delivering a haystack. */
function navigatePage(pg, withFilter) {
  if (!can(pg, 'v')) return;
  /* Leaving an open request form used to silently empty everything typed —
     the form re-rendered from a stale draft while still LOOKING open, which
     made the loss read as a bug. Capture before the page changes. */
  if (typeof scrView !== 'undefined' && scrView === 'form' && typeof captureScrHeader === 'function')
    captureScrHeader();
  page = pg;
  activeSidebarItem = pg;
  lastOpenedRecord = null;
  expandOwningDropdown(pg);
  /* Land in the channel you last used for THIS screen, or the one the journey
     says the stage belongs to. Carrying the previous page's channel across is
     what makes a walkthrough feel arbitrary — you approve on a phone, tap
     through to the challan, and are still holding a phone for a Finance
     screen that nobody uses on one. */
  channel = channelForPage(pg);
  resetFilters();          /* F09 — filters never follow you to another page */
  if (withFilter && withFilter.length === 2)
    pageFilters()['flt-' + statusClass(withFilter[0])] = withFilter[1];
  renderPage();
  syncUrl();
}

/* Route an identifier to whichever module owns it, by its prefix. Used by the
   ?open= deep link and by cross-references between screens. */
/* Every document in the journey belongs to exactly one deal. Mapping back to
   it is what lets the journey bar follow whatever you just opened. */
function dealIdOf(id) {
  const r = (typeof scr === 'function' && scr(id)) ||
            (typeof po === 'function' && po(id)) ||
            (typeof shipment === 'function' && shipment(id)) ||
            (typeof dnote === 'function' && dnote(id)) ||
            (typeof challan === 'function' && challan(id)) ||
            (typeof imr === 'function' && imr(id));
  if (!r) return null;
  return r.scrId || r.id || null;
}

function openRecord(id) {
  const go = (pg, fn) => {
    if (!can(pg, 'v')) { toast('Your position cannot open ' + id + '.', 'bad'); return; }
    page = pg; activeSidebarItem = pg; lastOpenedRecord = id;
    /* THE BAR FOLLOWS WHAT YOU OPENED. Without this it kept narrating whatever
       deal it had picked for itself, so the header could describe SUB-000318
       while the record on screen was SUB-000319 — two unrelated stories on one
       page, which is exactly the incoherence the bar exists to remove. */
    const deal = dealIdOf(id);
    if (deal) trackDeal(deal);
    expandOwningDropdown(pg);
    /* Same rule as navigatePage: web unless a decision is waiting for this
       person on the screen the record opens onto. */
    channel = channelForPage(pg);
    fn(); renderPage(); syncUrl();
  };
  if (typeof scr === 'function' && scr(id))        return go('scr',            () => { scrSelected = id; scrView = 'detail'; });
  if (typeof po === 'function' && po(id))          return go('orders',         () => { poSelected = id; poView = 'detail'; });
  if (typeof shipment === 'function' && shipment(id)) return go('shipments',   () => { shipSelected = id; shipView = 'detail'; });
  if (typeof dnote === 'function' && dnote(id))    return go('delivery-notes', () => { dnSelected = id; });
  if (typeof challan === 'function' && challan(id))return go('challans',       () => { chSelected = id; });
  /* An IMR opens its parent challan — that is where its receipts are listed. */
  if (typeof imr === 'function' && imr(id))
    return go('inward', () => { inwSelected = imr(id).challanId; });
  toast('There is no screen for ' + id + '.', 'bad');
}

/* True when openRecord would actually go somewhere. refLink asks first, so a
   dead identifier is never dressed up as a button that silently does nothing. */
function isRoutable(id) {
  if (!id) return false;
  return !!((typeof scr === 'function' && scr(id)) ||
            (typeof po === 'function' && po(id)) ||
            (typeof shipment === 'function' && shipment(id)) ||
            (typeof dnote === 'function' && dnote(id)) ||
            (typeof challan === 'function' && challan(id)) ||
            (typeof imr === 'function' && imr(id)));
}

/* ── Custom select ──────────────────────────────────────────────────────────
   Carried over from ADT.  Fixed-position menu, because every one of these
   opens inside an overflow:auto container that would clip an absolute one. */
/* WHETHER A FIELD IS SET IS TRACKED, NOT GUESSED.

   This used to derive "unset" by comparing the displayed text to the
   placeholder — so any real value that happened to equal its own placeholder
   was treated as empty. That was not cosmetic. Two live faults came out of it:

     · The order form passes taxCode 'GST 18%' with placeholder 'GST 18%', so
       getSelectValue() returned '' and capturePo() wiped the tax code on every
       save.
     · The logistics form passes mode 'Road' with placeholder 'Road', so the
       mode read back as '' and MODE_REQUIRED[''] was undefined — the entire
       mode-driven mandatory-field rule was skipped, and a shipment could be
       dispatched with no vehicle, driver or transporter at all.

   `data-unset` now records the fact explicitly, and the placeholder styling
   follows from it rather than from a string comparison. */
/* `onChange` names a global called with (value, id) the moment an option is
   picked. selectCustomOption has honoured data-onchange from the start — but
   no form ever set it, so every dependent-field relationship in the app
   (vendor → rate contracts, transport mode → required fields, reason →
   mandatory remarks) was inert until something else forced a repaint. This
   sixth parameter is what finally wires them. */
function customSelect(id, selected, options, placeholder, variant, onChange) {
  const safeId = String(id).replace(/[^a-zA-Z0-9_-]/g, '-');
  const opts = (options || []).map(o => String(o));
  const hasValue = selected != null && String(selected) !== '';
  const current = hasValue ? String(selected) : (placeholder || opts[0] || 'Select');
  const optHtml = opts.map(o =>
    '<button type="button" class="custom-select-option ' + (hasValue && o === current ? 'selected' : '') +
    '" data-value="' + attrSafe(o) + '" onclick="selectCustomOption(event,this)">' +
    '<span class="custom-select-text">' + esc(o) + '</span>' +
    '<span class="custom-select-check">&#10003;</span></button>').join('');
  return '<div class="custom-select ' + (variant || '') + '" id="' + safeId + '"' +
    ' data-value="' + attrSafe(hasValue ? current : '') + '"' +
    ' data-unset="' + (hasValue ? '0' : '1') + '"' +
    (onChange ? ' data-onchange="' + attrSafe(onChange) + '"' : '') + '>' +
    '<button type="button" class="custom-select-trigger" onclick="toggleCustomSelect(event,\'' + safeId + '\')">' +
    '<span class="' + (hasValue ? '' : 'placeholder') + '">' + esc(current) + '</span>' +
    '<svg class="custom-select-chevron" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.4"><polyline points="6 9 12 15 18 9"/></svg>' +
    '</button><div class="custom-select-menu">' + optHtml + '</div></div>';
}

function closeCustomSelects(exceptId) {
  document.querySelectorAll('.custom-select.open').forEach(s => {
    if (!exceptId || s.id !== exceptId) s.classList.remove('open');
  });
}

function toggleCustomSelect(event, id) {
  event.stopPropagation();
  const root = document.getElementById(id);
  if (!root) return;
  const open = root.classList.contains('open');
  closeCustomSelects(id);
  root.classList.toggle('open', !open);
  if (!open) {
    const trigger = root.querySelector('.custom-select-trigger');
    const menu = root.querySelector('.custom-select-menu');
    if (trigger && menu) {
      const r = trigger.getBoundingClientRect();
      placeAnchoredMenu(menu, r, { alignLeft: true, width: r.width });
    }
  }
}

function selectCustomOption(event, opt) {
  event.stopPropagation();
  const root = opt.closest('.custom-select');
  if (!root) return;
  const label = opt.querySelector('.custom-select-text');
  const trigger = root.querySelector('.custom-select-trigger span');
  root.dataset.value = label ? label.textContent.trim() : opt.textContent.trim();
  root.dataset.unset = '0';                       /* picking anything sets it */
  if (trigger && label) { trigger.innerHTML = label.innerHTML; trigger.classList.remove('placeholder'); }
  root.querySelectorAll('.custom-select-option').forEach(o => o.classList.remove('selected'));
  opt.classList.add('selected');
  root.classList.remove('open');
  if (root.dataset.onchange && typeof window[root.dataset.onchange] === 'function')
    window[root.dataset.onchange](root.dataset.value, root.id);
}

function getSelectValue(id) {
  const root = document.getElementById(id);
  if (!root) return '';
  if (root.dataset.unset === '1') return '';      /* the fact, not a guess */
  return root.dataset.value || '';
}

/* ── Anchored menu placement ────────────────────────────────────────────────
   Below if it fits, above if THAT fits, otherwise the roomier side with the
   height capped so the menu scrolls instead of leaving the viewport.  The
   ceiling is the bottom of the topbar, not the window: a menu that climbs over
   the bar covers the account switcher and reads as a panel belonging to
   nothing. */
const MENU_GAP = 6, MENU_EDGE = 10;

function fixedOrigin(el) {
  for (let p = el && el.parentElement; p && p !== document.documentElement; p = p.parentElement) {
    const cs = window.getComputedStyle(p);
    if ((cs.transform && cs.transform !== 'none') ||
        (cs.perspective && cs.perspective !== 'none') ||
        (cs.filter && cs.filter !== 'none') ||
        /transform|perspective|filter/.test(cs.willChange || '') ||
        /paint|layout|strict|content/.test(cs.contain || '')) {
      const r = p.getBoundingClientRect();
      return { x: r.left, y: r.top };
    }
  }
  return { x: 0, y: 0 };
}

function menuBounds() {
  let top = MENU_EDGE;
  const bar = document.querySelector('.topbar');
  if (bar) {
    const r = bar.getBoundingClientRect();
    if (r.height && r.bottom > 0) top = r.bottom + MENU_GAP;
  }
  return { top: top, bottom: window.innerHeight - MENU_EDGE };
}

function placeAnchoredMenu(menu, anchor, opts) {
  if (!menu || !anchor) return;
  opts = opts || {};
  menu.style.maxHeight = ''; menu.style.right = 'auto'; menu.style.bottom = 'auto';
  menu.style.top = '0px'; menu.style.left = '0px';
  if (opts.width) menu.style.width = opts.width + 'px';
  const mw = menu.offsetWidth, mh = menu.offsetHeight;
  const vw = window.innerWidth;

  let left = opts.alignLeft ? anchor.left : anchor.right - mw;
  left = Math.min(Math.max(MENU_EDGE, left), Math.max(MENU_EDGE, vw - mw - MENU_EDGE));

  const b = menuBounds();
  const below = b.bottom - anchor.bottom - MENU_GAP;
  const above = anchor.top - MENU_GAP - b.top;
  let top, cap;
  if (mh <= below)      { top = anchor.bottom + MENU_GAP; cap = below; }
  else if (mh <= above) { top = anchor.top - MENU_GAP - mh; cap = above; }
  else if (below >= above) { top = anchor.bottom + MENU_GAP; cap = below; }
  else                  { top = b.top; cap = above; }
  cap = Math.max(120, Math.min(cap, b.bottom - b.top));
  top = Math.min(Math.max(b.top, top), Math.max(b.top, b.bottom - Math.min(mh, cap)));

  const o = fixedOrigin(menu);
  menu.style.left = Math.round(left - o.x) + 'px';
  menu.style.top = Math.round(top - o.y) + 'px';
  menu.style.maxHeight = (cap < mh) ? Math.floor(cap) + 'px' : '';
  if (cap < mh) {
    const cur = menu.querySelector('.selected');
    menu.scrollTop = cur ? Math.max(0, cur.offsetTop - (cap - cur.offsetHeight) / 2) : 0;
  } else menu.scrollTop = 0;
}

/* A fixed menu does not travel with the thing it is anchored to, so closing is
   the honest response to a scroll.  A scroll that STARTED inside an open menu
   is the user reading it, and is ignored. */
function closeAnchoredMenus(e) {
  const t = e && e.target;
  if (t && t.closest && t.closest('.custom-select-menu, .hdr-dd-panel')) return;
  closeCustomSelects();
  closeHeaderMenus();
}
window.addEventListener('scroll', closeAnchoredMenus, true);
window.addEventListener('resize', closeAnchoredMenus);
document.addEventListener('click', e => {
  if (!e.target.closest('.custom-select')) closeCustomSelects();
  if (!e.target.closest('.hdr-dd-wrap')) closeHeaderMenus();
});
document.addEventListener('keydown', e => {
  if (e.key === 'Escape') { closeCustomSelects(); closeHeaderMenus(); }
});

