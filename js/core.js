/* The switcher is what makes the per-Team decision visible: pick two users in
   the same Team and the nav is identical; pick two in different Teams and it
   changes.  Position is shown alongside because it still drives the special
   actions and the commercial mask. */
function buildRoleSwitcher() {
  const groups = {};
  Object.keys(USERS).forEach(id => {
    const u = USERS[id];
    if (!u.team) return;         /* external users are not internal roles */
    (groups[u.team] = groups[u.team] || []).push(id);
  });
  let html = '';
  Object.keys(groups).forEach(teamId => {
    const t = TEAMS[teamId];
    html += '<div class="rs-group"><div class="rs-group-head">' + esc(t.name) +
            '<span class="rs-code">' + esc(teamId) + '</span></div>';
    groups[teamId].forEach(id => {
      const u = USERS[id];
      html += '<button class="hdr-dd-item' + (id === currentUserId ? ' rs-current' : '') +
              '" onclick="closeHeaderMenus();setCurrentUser(\'' + id + '\')">' +
              '<span class="rs-avatar">' + esc(initials(u.name)) + '</span>' +
              '<span class="rs-who"><span class="rs-name">' + esc(u.name) + '</span>' +
              '<span class="rs-pos">' + esc(positionLabel(u.position)) + '</span></span></button>';
    });
    html += '</div>';
  });
  return html;
}

