/* ── Text helpers ───────────────────────────────────────────────────────── */
function esc(v) {
  return String(v == null ? '' : v)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;')
    .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
function attrSafe(v) {
  return String(v == null ? '' : v).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
}
function statusClass(v) {
  return String(v).toLowerCase().replace(/[^a-z0-9]+/g, '-');
}

/* ── Numbers ────────────────────────────────────────────────────────────────
   Quantities carry three decimals because the BRD's own documents do
   (258.000 KG), and a BOM-ratio consumption has to be shown at the configured
   precision rather than rounded to look tidy. */
function fmtQty(n, dp) {
  if (n == null || n === '') return '';
  return Number(n).toLocaleString('en-IN', {
    minimumFractionDigits: dp == null ? 3 : dp,
    maximumFractionDigits: dp == null ? 3 : dp
  });
}
function fmtMoney(n) {
  if (n == null || n === '') return '';
  return '₹ ' + Number(n).toLocaleString('en-IN', { minimumFractionDigits: 0, maximumFractionDigits: 2 });
}

/* F30 · ONE DATE FORMAT.
   Dates arrive from two places — typed into a date input (ISO, "2026-10-02")
   and generated by stampNow ("8 Oct 2026") — and both were being printed raw,
   so two formats sat on the same row. Everything renders through here. */
const MONTHS = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];
function fmtDate(v) {
  if (!v) return '';
  const s = String(v);
  const m = s.match(/^(\d{4})-(\d{2})-(\d{2})/);
  if (!m) return s;                                  /* already display form */
  return Number(m[3]) + ' ' + MONTHS[Number(m[2]) - 1] + ' ' + m[1];
}

/* ── Status tones ───────────────────────────────────────────────────────────
   ONE MEANING PER HUE, straight from the ADT token contract:
     ok    settled + positive      wait  still in flight
     bad   settled + negative      info  purely informational
     idle  no longer in play

   Amber is "waiting", never "bad" — which is why Returned and Short-Closed are
   amber (someone still has to act) while Rejected and Cancelled are red (the
   record has stopped).  Voided is idle, not red: nothing failed, the document
   simply no longer applies. */
const STATUS_TONE = {
  /* Deal */
  'created': 'info', 'sent-for-approval': 'wait', 'returned': 'wait',
  'modified': 'wait', 'approved': 'ok', 'rejected': 'bad', 'closed': 'idle',
  /* Order */
  'draft': 'idle', 'short-closed': 'wait',
  /* Shipment */
  'not-raised': 'idle', 'freezed-outbound-release': 'wait',
  'challan-generated': 'wait', 'gate-cleared': 'ok', 'cancelled': 'bad',
  /* Stage */
  'in-progress': 'wait', 'completed': 'ok',
  /* Delivery Note */
  'generated': 'info', 'voided': 'idle',
  /* Challan */
  'overdue': 'bad',
  /* IMR */
  'confirmed': 'ok',
  /* Material position */
  'available': 'ok', 'reserved': 'wait', 'at-vendor-in-transit': 'info',
  'returned-to-store': 'ok',
  /* Line status */
  'open': 'info', 'partially-received': 'wait', 'fully-received': 'ok',
  /* Master records */
  'active': 'ok', 'inactive': 'idle'
};
function statusTone(v) { return STATUS_TONE[statusClass(v)] || 'idle'; }

/* Display names for statuses whose BRD term misleads or overflows a pill.
   "Freezed Outbound Release" reads as held/blocked — the opposite of what
   happened — and was being amputated mid-word in narrow columns. The BRD term
   stays in the tooltip so an auditor can match the document. */
const STATUS_DISPLAY = {
  'Freezed Outbound Release': 'Released to dispatch',
  'Challan Generated': 'Challan raised',
  'Sent for Approval': 'Awaiting approval'
};

/* A status badge.  PILL shape, always — the shape system says a pill is a
   read-only state and is never clickable.  Never build one by hand. */
function sbStatus(value, label) {
  if (!value) return '';
  const shown = label || STATUS_DISPLAY[value] || value;
  const tip = (!label && STATUS_DISPLAY[value]) ? ' title="' + attrSafe(value) + '"' : '';
  return '<span class="sb-st sb-st-' + statusTone(value) + '"' + tip + '>' + esc(shown) + '</span>';
}

